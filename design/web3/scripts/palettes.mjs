/**
 * Palette loading, CSS generation and the contrast rules every palette must meet.
 * Shared by the build script and the unit tests.
 */
import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { contrast } from "../src/core/color.js";

export const PALETTE_FILE = fileURLToPath(new URL("../src/tokens/palettes.json", import.meta.url));

export const REQUIRED_KEYS = [
    "bg", "bg-alt", "surface", "surface-raised", "line", "line-strong",
    "fg", "fg-muted", "accent", "accent-text", "on-accent", "ok", "bad", "focus",
];

/** [foreground, background, minimum ratio, why] */
export const CONTRAST_RULES = [
    ["fg", "bg", 7, "body text"],
    ["fg", "surface", 7, "text on cards"],
    ["fg", "surface-raised", 7, "text on raised cards"],
    ["fg-muted", "bg", 4.5, "secondary text"],
    ["fg-muted", "surface", 4.5, "secondary text on cards"],
    ["fg-muted", "surface-raised", 4.5, "secondary text on raised cards"],
    ["accent-text", "bg", 4.5, "accent used as text"],
    ["accent-text", "surface", 4.5, "accent text on cards"],
    ["on-accent", "accent", 4.5, "text on accent fill"],
    ["ok", "surface", 4.5, "success text"],
    ["bad", "surface", 4.5, "error text"],
    ["focus", "bg", 3, "focus ring (non-text)"],
    ["focus", "surface", 3, "focus ring on cards (non-text)"],
];

export const CHROME_RULES = [
    ["fg", "bg", 7],
    ["fg", "surface", 7],
    ["muted", "bg", 4.5],
    ["muted", "surface", 4.5],
    ["on", "hi", 4.5],
];

export async function loadPalettes() {
    return JSON.parse(await readFile(PALETTE_FILE, "utf8"));
}

/** Every failing pair, as readable strings. Empty array means all good. */
export function contrastFailures(palettes) {
    const failures = [];
    for (const [id, themes] of Object.entries(palettes.proposals)) {
        for (const [theme, palette] of Object.entries(themes)) {
            for (const key of REQUIRED_KEYS) if (!(key in palette)) failures.push(`${id}/${theme}: missing "${key}"`);
            for (const [fg, bg, min, why] of CONTRAST_RULES) {
                const ratio = contrast(palette[fg], palette[bg]);
                if (ratio < min) failures.push(`${id}/${theme}: ${fg} on ${bg} is ${ratio.toFixed(2)}, needs ${min} (${why})`);
            }
        }
    }
    for (const [theme, palette] of Object.entries(palettes.chrome)) {
        for (const [fg, bg, min] of CHROME_RULES) {
            const ratio = contrast(palette[fg], palette[bg]);
            if (ratio < min) failures.push(`chrome/${theme}: ${fg} on ${bg} is ${ratio.toFixed(2)}, needs ${min}`);
        }
    }
    return failures;
}

const declarations = (palette, prefix = "") =>
    Object.entries(palette)
        .map(([key, value]) => `--${prefix}${key}: ${value.toLowerCase()};`)
        .join(" ");

/** CSS custom properties for the explorer chrome (host theme aware) and every proposal theme. */
export function paletteCss(palettes) {
    const { chrome, proposals } = palettes;
    const lines = [
        "/* Generated by scripts/build.mjs from src/tokens/palettes.json. Do not edit by hand. */",
        `:root { ${declarations(chrome.light, "x-")} }`,
        `@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) { ${declarations(chrome.dark, "x-")} color-scheme: dark; } }`,
        `:root[data-theme="dark"] { ${declarations(chrome.dark, "x-")} color-scheme: dark; }`,
    ];
    for (const [id, themes] of Object.entries(proposals)) {
        for (const theme of ["dark", "light"]) {
            lines.push(`.stage[data-proposal="${id}"][data-theme="${theme}"] { ${declarations(themes[theme])} color-scheme: ${theme}; }`);
        }
    }
    return `${lines.join("\n")}\n`;
}
